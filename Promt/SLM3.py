def get_slm3_prompt(question_json_text, student_answer_text):
    """
    SLM3 - 語言層評分 (純 JSON 結構化思維鏈版)

    特點：
    - 強制將分析置於 JSON 欄位首位。
    - 不輸出任何 JSON 之外的解釋或 Markdown 包裝。
    - 維持高資訊密度的極簡指令。
    """
    return f"""
{question_json_text}

{student_answer_text}

評分層定義：
- 判斷層次：語言層（Syntax）
- 評分面向：語法與運算結構
- 核心判斷問題：程式是否「能正常執行」或「學生答案文字是否指出正確輸出」。
- 判斷內容：
  * 是否存在語法錯誤。
  * 是否存在型別錯誤。
  * 是否缺少必要的基本程式結構。
  * 運算式、條件式、迴圈、方法呼叫與變數使用是否具備合法結構。
- 僅依據程式語法、型別與基本運算結構判斷，不考慮程式功能或邏輯是否正確，也不考慮是否依照題目指定方式撰寫。

評分規則：
1. 僅依據上述「語言層」定義評分。
2. 逐項比對每個 criterion：完全符合=1，不符合、部分符合=0。
3. 每個 criterion 必須只依據語法、型別與基本程式結構判斷，不得引用行為層或規範層理由。
4. 若程式邏輯錯誤，但語法與型別合法，不能僅因邏輯錯誤而判定語言層不符合。
5. 若未使用題目指定的控制項、方法或格式，但程式結構本身合法，不能僅因未遵循指定寫法而判定語言層不符合。
6. 必須先在 "analysis" 中逐項寫下每個 criterion 的判斷依據，再產生後續分數。
7. 只輸出以下 JSON，嚴禁任何其他文字、解釋或 Markdown 標籤：
8. 如果學生提供的答案是『預期輸出結果』的文字描述，根據該描述判斷語法、型別與基本程式結構是否正確，並在 "analysis" 中說明理由。

{{
  "question_id": "...",
  "layer": "syntax",
  "analysis": "在這裡逐項推導每個語言層準則，檢查語法、型別、運算結構與基本程式結構是否正確...",
  "criteria_check": [
    {{
      "criterion": "①",
      "status": 0
    }}
  ],
  "total_criteria": N,
  "met_criteria": M,
  "syntax_score": "M/N"
}}
"""